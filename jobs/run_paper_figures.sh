#!/bin/bash
# Publication figure generation for the cancer trajectory atlas paper.
#
# CPU-only read-only plotting over existing result files on $SCRATCH.
# Does NOT re-run the pipeline, retrain scVI, rebuild the feature cache,
# or modify any adata/results file.
#
# Usage:
#   sbatch ~/cancer_trajectory_atlas/jobs/run_paper_figures.sh
#   sbatch ~/cancer_trajectory_atlas/jobs/run_paper_figures.sh 3,5,6,7
#   sbatch ~/cancer_trajectory_atlas/jobs/run_paper_figures.sh 2,3,4,5,6,7
#
# $1 = comma-separated figure numbers to generate (default: 3,5,6,7)
#
# Figures 2 and 4 require the pooled no-correction PAGA run to exist at
# $SCRATCH/results/runs_paga/all_noharmony/full (generated by submit_paga_runs.sh).
# If that dir is absent, pass only figures 3,5,6,7.
#
# Figures 1 (workflow schematic) and 8 (holey-ness validation) are out of
# scope and will be rejected with an error if requested.

#SBATCH --account=def-lmarti46
#SBATCH --time=00:15:00
#SBATCH --cpus-per-task=1
#SBATCH --mem=4G
#SBATCH --job-name=paper_figures
#SBATCH --output=logs/paper_figures-%j.out

set -euo pipefail

mkdir -p logs

# ── Figure selector ───────────────────────────────────────────────────────────
FIGURE_SELECTOR="${1:-3,5,6,7}"

# ── Input directories (all absolute paths on $SCRATCH) ────────────────────────
SCVI_RUN_DIR="$SCRATCH/results/atlas_none_scvi"
HARMONY_RUN_DIR="$SCRATCH/results/runs_paga/all_harmony/full"
SECTION1_DIR="$SCRATCH/results/per_section/atlas_2M-1"
SECTION2_DIR="$SCRATCH/results/per_section/atlas_2M-2"
NOCORRECTION_DIR="$SCRATCH/results/runs_paga/all_noharmony/full"

# ── Output ────────────────────────────────────────────────────────────────────
OUT_DIR="$SCRATCH/results/paper_figures"

echo "============================================"
echo "  Cancer Trajectory Atlas — Paper Figures"
echo "  Job ID: ${SLURM_JOB_ID:-local}"
echo "  Figures: $FIGURE_SELECTOR"
echo "  Output:  $OUT_DIR"
echo "============================================"

module load StdEnv/2023 python/3.11 gcc opencv openslide openblas hdf5 igraph
source ~/envs/atlas/bin/activate

mkdir -p "$OUT_DIR"
cd ~

python -m cancer_trajectory_atlas.figures.make_paper_figures \
    --scvi-run-dir              "$SCVI_RUN_DIR"      \
    --harmony-run-dir           "$HARMONY_RUN_DIR"   \
    --section1-dir              "$SECTION1_DIR"      \
    --section2-dir              "$SECTION2_DIR"      \
    --pooled-nocorrection-dir   "$NOCORRECTION_DIR"  \
    --output-dir                "$OUT_DIR"           \
    --dpi                       300                  \
    --figures                   "$FIGURE_SELECTOR"

echo ""
echo "============================================"
echo "  PAPER FIGURES COMPLETE"
echo "============================================"
echo ""
echo "Output files:"
ls -1 "$OUT_DIR"/*.pdf "$OUT_DIR"/*.png 2>/dev/null | sed 's/^/  /'
echo ""

# ── Append working log to PROJECT_STATE.md ────────────────────────────────────
TODAY=$(date +%Y-%m-%d)
JOBID=${SLURM_JOB_ID:-local}

cat >> ~/cancer_trajectory_atlas/PROJECT_STATE.md << WORKLOG

---

## Working Log — Paper Figures ($TODAY)

**Job:** \`jobs/run_paper_figures.sh\`
**Module:** \`cancer_trajectory_atlas/figures/make_paper_figures.py\`
**Job ID:** $JOBID  **Figures generated:** $FIGURE_SELECTOR

### Input files per figure

| Figure | Output stem | Primary inputs |
|---|---|---|
| 3 | \`fig3_batch_mixing\` | \`atlas_none_scvi/batch_mixing.json\` (raw_pca, scvi, chance_baseline), \`runs_paga/all_harmony/full/batch_mixing.json\` (harmony) |
| 5 | \`fig5_loo_reproducibility\` | \`per_section/atlas_{2M-1,2M-2}/loo_summary/loo_summary.csv\` (slide_name, spearman_rho) |
| 6 | \`fig6_morphology_correlates\` | \`per_section/atlas_{2M-1,2M-2}/validation.json\` (feature_correlations -> rho) |
| 7 | \`fig7_cellularity_confound\` | \`per_section/atlas_{2M-1,2M-2}/cellularity_confound/cellularity_confound.json\` (features -> raw_rho, partial_rho) |
| 2 | \`fig2_pooled_nocorrection\` | \`runs_paga/all_noharmony/full/figures/qc_paga_topology.png\`, \`qc_umap_section_vs_cluster.png\` |
| 4 | \`fig4_per_section_panel\` | \`per_section/atlas_{2M-1,2M-2}/figures/{qc_paga_topology,diffusion_3d,fig4_umap_pseudotime,fig5_pt_violins}.png\` |

### Key values (see logs/paper_figures-$JOBID.out for exact numbers)

The job log is the authoritative record of every value that went into the manuscript.
Per-figure numeric output is printed by the module before each figure is saved.

### Design notes

- Figures 1 (schematic) and 8 (holey-ness) are out of scope and not generated.
- Per-section batch_mixing.json files are excluded from Figure 3 (purity = 1.0 trivially when all slides share one section_number).
- Figure 3 raw_pca reads from the scVI run (most recent pooled run); harmony reads from the Harmony PAGA run.
- Cellularity confound JSON key is \`partial_perm_p\` (not \`perm_p\`); status (|partial_rho| >= 0.1) derived at plot time.
- All figures saved as both PDF (embedded TrueType fonts, pdf.fonttype=42) and PNG at 300 dpi.
- Colourblind-safe Okabe-Ito palette: 2M-1 = #0072B2 (blue), 2M-2 = #E69F00 (orange).

WORKLOG

echo "PROJECT_STATE.md updated."
